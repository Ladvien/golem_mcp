import json
import struct
import sys

import numpy as np

sys.path.insert(0, "/home/ladvien/skintokens/repo")

UP, LAT, DEP = 1, 2, 0    # glTF Y-up; arm span on Z, body depth on X
GLTF_JSON_CHUNK = 0x4E4F534A




