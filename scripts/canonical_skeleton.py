#!/usr/bin/env python
"""Fit a Mixamo-named skeleton to a generated character, and restore names after rigging.

Run by the SkinTokens venv (python 3.11) - it owns the Asset/BpyParser writer this
depends on. Two subcommands:

    canonical_skeleton.py fit           mesh.glb -> mesh+armature.glb
    canonical_skeleton.py restore-names rigged.glb + reference.glb -> named.glb

WHY A SUPPLIED SKELETON AT ALL
------------------------------
`rig_model` normally invents a skeleton per asset. Measured across the library
that gives 52, 58 and 28 bones, all named bone_N - so no animation is shareable
between two characters and no Mixamo clip can drive any of them. TokenRig's
`use_skeleton` path skins to an armature the input already carries, which turns it
from a skeleton generator into a skinning solver. The README calls skinning "the
part the model is genuinely good at", and it removes the documented 47-vs-44-joint
nondeterminism, since only skinning is then sampled.

Verified on female_base_v5: input and output parent arrays come back
byte-identical, symmetry 0.87 against the README's 0.86 reference, zero dead
vertices, zero unweighted bones.

TWO NON-OBVIOUS CONSTRAINTS
---------------------------
1. Write the GLB with SkinTokens' own `Asset.from_data` + `BpyParser.export_asset`.
   Building the armature with bpy and exporting via `export_scene.gltf` yields
   `"skins": 0` - JOINTS_0/WEIGHTS_0 attributes with no skin object, which Blender
   itself re-imports as loose nodes and `get_armature()` cannot see. The cause is
   `parent_set(type='ARMATURE_AUTO')`, whose bone-heat solver reports "failed to
   find solution for one or more bones".
2. Restore names AFTER rigging. `rig_package/parser/bpy.py:532` falls back to
   `bone_{i}` whenever the predicted Asset has `joint_names=None`, which it always
   does - names are read on input for tokenisation and never carried into the
   result. Joint ORDER survives (the identical parent arrays prove it), so
   renaming by index is exact.

STATUS: WORKING VIA --from-rig. PURE GEOMETRY DOES NOT GENERALISE.
------------------------------------------------------------------
`fit --from-rig <rigged.glb>` is the only path: landmarks come from a generated
skeleton. Verified on all three library characters: each yields a byte-identical
23-bone Mixamo core, and one named pose drives characters of different heights
with no per-character setup (6/6 bones found, ~91% of vertices moved on both a
1.0 m dwarf and a 1.7 m base body, displacement scaling with height as LBS should).
Measured world-space mirror symmetry of the fitted core is 1.000 - by construction,
since it is built from resampled symmetric pairs. (Do NOT quote _skeleton_report's
symmetry for this: it mirrors LOCAL node translations, so it is not
rotation-invariant and reads 0.913 or 0.652 for the same skeleton depending only
on the file's up-axis.)

Geometric landmark detection was tried first and measured against the same three
characters. It failed differently on each, and the code is DELETED rather than
kept as a fallback - a second path that never works is only a way to get magic
results. Recorded here so it is not attempted again:

  female_base_v5  T-pose arms are CONTIGUOUS with the torso, so the central-run
                  width at shoulder height is 1.674 - the whole arm span. Nothing
                  distinguishes torso from arm, and the fitter labels the real
                  arms as "wings".
  succubus_warden wings are wide at every height, so total width never shows the
                  arm jump a T-posed body does. Fixed by measuring the central
                  run - which is what then broke the T-pose case above.
  forge_warden    a stocky dwarf has NO neck pinch: central width runs 0.31 ->
                  0.22 flat from 0.37 to 0.90 of height. The detector found a
                  0.60 fold in his tabard instead.

This is precisely what HumanRig (arXiv 2412.02317) reports of geometric and
GNN-based rigging: they "struggle with complex 3D models, particularly those
generated by AI ... irregular shapes, detailed clothing or accessories, and
differing head-to-body ratios". Their answer was a learned 2D pose prior (PGSE):
render a front view, run a fine-tuned RTMPose, lift to 3D with the known camera.

The A-pose-is-enforced argument for going geometric was mine, and measurement
falsified it. --from-rig replaces it: TokenRig's generated skeleton demonstrably
finds the limbs on these assets, so it supplies the landmarks that slice geometry
could not. Three things were needed to read it correctly:

  * accumulate full TRS matrices, not translations - bone nodes carry rotation,
    and each offset is expressed along its parent's rotated axis. Summing
    translations alone put the feet at mid-height.
  * classify by STRUCTURE, not coordinates. The spine is the path to the highest
    leaf and limbs hang off it. Extremes only work for a T-pose: on the arms-down
    succubus the most-lateral leaf was a foot, on the dwarf it was the head.
  * choose limbs as symmetric PAIRS. Ranking branches individually kept picking
    horn stubs as arms; mirroring is a far stronger signal than any single
    branch's position, and it handles A-pose and T-pose under one rule.

Cost: one extra rig pass, since the generated skeleton must exist first. rig_model
runs both passes itself.
"""

