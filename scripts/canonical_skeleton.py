def read_skeleton(path):
    """(names, parents, world joint positions) from a rigged GLB's skin."""
    d = open(path, "rb").read()
    ln = struct.unpack("<I", d[12:16])[0]
    doc = json.loads(d[20:20 + ln].decode("utf-8"))
    nodes, joints = doc["nodes"], doc["skins"][0]["joints"]
    parent_of = {}
    for i, n in enumerate(nodes):
        for c in n.get("children", []):
            parent_of[c] = i

    def local(n):
        """Bone nodes carry ROTATION as well as translation. Accumulating
        translations alone puts the feet at mid-height, because each offset is
        expressed along its parent's rotated axis."""
        if "matrix" in n:
            return np.array(n["matrix"], dtype=float).reshape(4, 4).T
        m = np.eye(4)
        if "rotation" in n:
            x, y, z, w = n["rotation"]
            m[:3, :3] = np.array([
                [1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
                [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
                [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]])
        if "scale" in n:
            m[:3, :3] = m[:3, :3] @ np.diag(n["scale"])
        if "translation" in n:
            m[:3, 3] = n["translation"]
        return m

    def world(i):
        chain, k = [], i
        while k is not None:
            chain.append(k)
            k = parent_of.get(k)
        m = np.eye(4)
        for k in reversed(chain):
            m = m @ local(nodes[k])
        return m[:3, 3]

    slot = {n: s for s, n in enumerate(joints)}
    return ([nodes[i].get("name", "") for i in joints],
            np.array([slot.get(parent_of.get(i), -1) for i in joints], dtype=int),
            np.stack([world(i) for i in joints]))


def classify(parents, pos):
    """Spine, legs, arms and leftovers, from structure rather than coordinates.

    Picking limbs by extreme coordinates only works for a T-pose: on the
    arms-down succubus the most-lateral leaf was a foot, and on the dwarf it was
    the head. The spine is the path to the highest leaf; everything else hangs
    off it, and limbs are chosen as symmetric PAIRS - by far the strongest signal.
    """
    n = len(parents)
    children = {i: [] for i in range(n)}
    for i, p in enumerate(parents):
        if p >= 0:
            children[p].append(i)
    leaves = [i for i in range(n) if not children[i]]
    lo, hi = pos[:, UP].min(), pos[:, UP].max()
    h = max(hi - lo, 1e-9)

    def frac(i):
        return float((pos[i, UP] - lo) / h)

    def path(i):
        out = []
        while i >= 0:
            out.append(i)
            i = parents[i]
        return out[::-1]

    spine = path(max(leaves, key=frac))
    on_spine = set(spine)

    def subtree(i):
        out, stack = [], [i]
        while stack:
            k = stack.pop()
            out.append(k)
            stack.extend(children[k])
        return out

    # WHICH AXIS IS LEFT-TO-RIGHT. This was hardcoded to glTF Z and is wrong for
    # most assets - measured across the library, arm-tip separation per axis:
    #
    #     emberwake_herald  [0.411 0.000 0.000]   lateral is X
    #     forge_warden      [0.609 0.035 0.016]   lateral is X
    #     succubus_warden   [0.375 0.000 0.000]   lateral is X
    #     female_base_v5    [0.000 0.000 1.616]   lateral is Z
    #
    # so on three of four, every "lateral" measurement below was reading DEPTH.
    # Sorting limbs by front/back carries no left/right information at all, which
    # is why side assignment behaved randomly and why arms could end up labelled
    # against the legs. Limbs spread sideways far more than fore-and-aft, so the
    # widest-spread horizontal axis is the lateral one.
    off_spine = [c for node in spine for c in children[node] if c not in on_spine]
    horiz = [k for k in (0, 1, 2) if k != UP]
    if off_spine:
        cents = np.stack([np.mean(pos[subtree(c)], axis=0) for c in off_spine])
        lat = max(horiz, key=lambda k: float(cents[:, k].max() - cents[:, k].min()))
    else:
        lat = LAT
    # Body axis from the SPINE: a median over all joints is dragged sideways by
    # whichever limb carries more bones.
    ctr = float(np.median(pos[spine, lat]))

    branches = []
    for node in spine:
        for c in children[node]:
            if c in on_spine:
                continue
            st = subtree(c)
            far = max(st, key=lambda k: abs(pos[k, lat] - ctr))
            branches.append({
                "root": c, "at": node, "at_frac": frac(node), "size": len(st),
                "min_frac": min(frac(k) for k in st),
                "max_frac": max(frac(k) for k in st),
                "lat_reach": float(abs(pos[far, lat] - ctr) / h),
                "lat_mean": float(np.mean(pos[st, lat]) - ctr),
                "nodes": st,
            })

    def best_pair(cands, cost):
        best, chosen = None, None
        for i in range(len(cands)):
            for j in range(i + 1, len(cands)):
                a, b = cands[i], cands[j]
                sym = (abs(a["at_frac"] - b["at_frac"])
                       + abs(a["size"] - b["size"]) / max(a["size"], b["size"], 1))
                score = sym + cost(a, b)
                if best is None or score < best:
                    best, chosen = score, (a, b)
        return list(chosen) if chosen else []

    def extent(b):
        return (b["max_frac"] - b["min_frac"]) + b["lat_reach"]

    legs = best_pair(branches, lambda a, b: a["min_frac"] + b["min_frac"])
    if not legs:
        legs = sorted(branches, key=lambda b: b["min_frac"])[:2]
    rest = [b for b in branches if b not in legs]
    # size >= 3 and real extent: ranking on branch height alone picked the
    # succubus's horn stubs (size 2, spanning 0.85-0.92) as arms.
    cand = [b for b in rest
            if b["at_frac"] > 0.45 and b["min_frac"] > 0.15 and b["size"] >= 3]
    arms = best_pair(cand, lambda a, b: (2.0 - a["at_frac"] - b["at_frac"])
                     - 1.5 * (extent(a) + extent(b)))
    extra = [b for b in rest if b not in arms]
    for pair in (legs, arms):                      # left = greater lateral
        if len(pair) == 2 and pair[0]["lat_mean"] < pair[1]["lat_mean"]:
            pair.reverse()
    return {"spine": spine, "legs": legs, "arms": arms, "extra": extra,
            "lat_axis": lat, "lat_center": ctr,
            "children": children, "parents": parents, "pos": pos, "height": float(h)}


def longest_line(c, branch):
    """The main limb line: longest root-to-leaf path inside a branch subtree."""
    children, best = c["children"], None
    stack = [[branch["root"]]]
    while stack:
        p = stack.pop()
        kids = children[p[-1]]
        if not kids:
            if best is None or len(p) > len(best):
                best = p
        for k in kids:
            stack.append(p + [k])
    return best or [branch["root"]]


def t_where(pos, line, key, target, lo=0.0, hi=1.0, steps=200):
    """Arc-length fraction along `line` at which key(point) first reaches `target`.

    Used to anchor joints to ANATOMY rather than to a chain index. The generated
    skeleton's branch points are not joints: an arm chain starts at the clavicle
    root beside the neck (measured at 0.93 H) and a leg chain starts at the pelvis
    attachment (0.58 H), so sampling either at a fixed small t puts the shoulder in
    the character's ear and the femur head in its belly.
    """
    prev_t, prev_v = lo, key(resample(pos, line, [lo])[0])
    for i in range(1, steps + 1):
        t = lo + (hi - lo) * i / steps
        v = key(resample(pos, line, [t])[0])
        if (prev_v - target) * (v - target) <= 0 and abs(v - prev_v) > 1e-12:
            return prev_t + (t - prev_t) * (target - prev_v) / (v - prev_v)
        prev_t, prev_v = t, v
    return hi


def resample(pos, line, ts):
    """Positions at arc-length fractions along a joint polyline."""
    pts = pos[line]
    if len(pts) == 1:
        return [pts[0] for _ in ts]
    d = np.concatenate([[0.0], np.cumsum(np.linalg.norm(np.diff(pts, axis=0), axis=1))])
    total = d[-1] if d[-1] > 1e-9 else 1.0
    return [np.array([np.interp(t * total, d, pts[:, k]) for k in range(3)]) for t in ts]



def mixamo_from_generated(rigged_glb, links=3):
    """Mixamo skeleton placed from a GENERATED skeleton's own limb chains.

    Geometric landmark detection was tried first and does not generalise - see the
    status note above. TokenRig's generated skeleton does find the limbs on these
    assets (symmetry 0.86-0.87 library-wide), so it serves as the landmark source
    that slice geometry could not. Costs one extra rig pass.
    """
    _names, parents, pos = read_skeleton(rigged_glb)
    c = classify(parents, pos)
    spine, legs, arms = c["spine"], c["legs"], c["arms"]
    if len(legs) < 2 or len(arms) < 2:
        raise SystemExit(
            f"could not identify two legs and two arms in {rigged_glb} "
            f"(found {len(legs)} legs, {len(arms)} arms). The generated skeleton is "
            "too degenerate to use as a landmark source."
        )

    hips_i = min(b["at"] for b in legs)          # spine node the legs hang from
    sh_i = max(b["at"] for b in arms)            # spine node the arms hang from
    si = {n: k for k, n in enumerate(spine)}
    torso = spine[si[hips_i]:si[sh_i] + 1] or [hips_i, sh_i]
    upper = spine[si[sh_i]:] or [sh_i]

    # WHICH SIDE IS WHICH. classify() calls the greater lateral coordinate "left",
    # which is arbitrary - it depends on which way the character happens to face.
    # forge_warden came out mirrored, and a mirrored rig flips the lateral axis, so
    # retarget_animation's body frame flips with it, reads a 180 degree yaw, and
    # plays the walk mirrored. The feet settle it: the last segment of a leg chain
    # is the foot, and feet point where the character faces.
    up_v = pos[sh_i] - pos[hips_i]
    up_v = up_v / max(np.linalg.norm(up_v), 1e-9)
    toe_v = np.zeros(3)
    for b in legs:
        ln = longest_line(c, b)
        if len(ln) >= 2:
            toe_v = toe_v + (pos[ln[-1]] - pos[ln[-2]])
    toe_v = toe_v - up_v * float(toe_v @ up_v)
    lat_v = pos[legs[1]["root"]] - pos[legs[0]["root"]]
    # Handedness must match the clip convention, not merely be self-consistent.
    # Measured against a Mixamo rig, every one of ITS Left bones sits at +lat where
    # lat = up x fwd; ours sat at -lat. Internally consistent, mirrored against the
    # world. A mirror is not a rotation, so a rotation-based retarget cannot
    # reproduce it: the delta that swings a +lat arm forward swings a -lat arm
    # BACKWARD. Legs point down, so their fore/aft response does not depend on which
    # side they are on - which is exactly why legs retargeted correctly while arms
    # inverted, and why this hid for so long.
    #
    # (a x b).c = det[a,b,c], so this test is lat_v . (up x fwd), and the Mixamo
    # convention is Left at +lat, hence Right-minus-Left at NEGATIVE lat.
    if float(np.cross(lat_v, up_v) @ toe_v) > 0:
        legs = legs[::-1]
        arms = arms[::-1]

    hips_up = float(pos[hips_i, UP])
    height = c["height"]
    lo_up = float(pos[:, UP].min())

    # Sample both limbs BEFORE building the spec: the pelvis is placed against the
    # femoral heads, so they have to be known first.
    limb = {}
    for tag, arm_b, leg_b in (("Left", arms[0], legs[0]), ("Right", arms[1], legs[1])):
        arm_line = longest_line(c, arm_b)
        # Shoulder by HEIGHT, not by lateral offset. Once the lateral axis was
        # fixed, the offset rule stopped discriminating: an arm chain clears
        # hip_half*1.15 within its first segment, so the joint sat back at the
        # clavicle root at 0.94 H. Height separates clavicle from humerus directly.
        t_sh = t_where(pos, arm_line, lambda q: float(q[UP]), lo_up + SHOULDER_FRAC * height)
        t_sh = min(max(t_sh, 0.05), 0.35)
        t_elbow = t_sh + (0.9 - t_sh) * 0.5
        # The extra 1.0 sample is the hand TIP - the chain already runs that far, so
        # the tip is measured rather than extrapolated.
        arm_pts = resample(pos, arm_line, [0.0, t_sh, t_elbow, 0.9, 1.0])

        leg_line = longest_line(c, leg_b)
        # Femoral head sits BELOW the pelvis attachment the chain starts at, or the
        # thigh pivots from inside the belly. Measured as a fraction of BODY height
        # the drop is far too big for short legs - it put the dwarf's femur head at
        # 0.42 H - so it is clamped tight.
        t_hip = t_where(pos, leg_line, lambda q: float(q[UP]), hips_up - 0.035 * height)
        t_hip = min(max(t_hip, 0.0), 0.10)
        leg_pts = resample(pos, leg_line, [t_hip, 0.5, 0.88, 1.0])
        limb[tag] = (arm_pts, leg_pts)

    leg_len = float(np.mean([
        np.linalg.norm(limb[t][1][0] - limb[t][1][3]) for t in ("Left", "Right")
    ]))
    femur_mid = (limb["Left"][1][0] + limb["Right"][1][0]) / 2

    spec, order = [], {}

    def add(name, parent, pos_):
        order[name] = len(spec)
        spec.append((name, order[parent] if parent else -1, np.asarray(pos_, float)))

    t = resample(pos, torso, [0.0, 0.33, 0.66, 1.0])
    # Pelvis against the femoral heads, not at the spine node the legs branch from -
    # that node is up inside the belly.
    add("mixamorig:Hips", None, femur_mid + up_v * (HIP_ABOVE_FEMUR * leg_len))
    add("mixamorig:Spine", "mixamorig:Hips", t[1])
    add("mixamorig:Spine1", "mixamorig:Spine", t[2])
    add("mixamorig:Spine2", "mixamorig:Spine1", t[3])
    u = resample(pos, upper, [0.25, 0.6, 1.0])
    add("mixamorig:Neck", "mixamorig:Spine2", u[0])
    add("mixamorig:Head", "mixamorig:Neck", u[1])
    add("mixamorig:HeadTop_End", "mixamorig:Head", u[2])

    for tag in ("Left", "Right"):
        a, g = limb[tag]
        add(f"mixamorig:{tag}Shoulder", "mixamorig:Spine2", a[0])
        add(f"mixamorig:{tag}Arm", f"mixamorig:{tag}Shoulder", a[1])
        add(f"mixamorig:{tag}ForeArm", f"mixamorig:{tag}Arm", a[2])
        add(f"mixamorig:{tag}Hand", f"mixamorig:{tag}ForeArm", a[3])
        add(f"mixamorig:{tag}Hand_End", f"mixamorig:{tag}Hand", a[4])

        add(f"mixamorig:{tag}UpLeg", "mixamorig:Hips", g[0])
        add(f"mixamorig:{tag}Leg", f"mixamorig:{tag}UpLeg", g[1])
        add(f"mixamorig:{tag}Foot", f"mixamorig:{tag}Leg", g[2])
        add(f"mixamorig:{tag}ToeBase", f"mixamorig:{tag}Foot", g[3])
        # The leg chain ends at the toe, so the tip is extrapolated along the foot.
        step = g[3] - g[2]
        nrm = float(np.linalg.norm(step))
        step = step / nrm if nrm > 1e-9 else -up_v
        add(f"mixamorig:{tag}Toe_End", f"mixamorig:{tag}ToeBase",
            g[3] + step * (TOE_TIP_FRAC * leg_len))

    # Leftover chains keep their geometry as named extras. Outside the mixamorig
    # namespace on purpose: retargeting drives mixamorig:* and ignores these, which
    # is what lets a standard clip run on a winged character.
    lo = pos[:, UP].min()
    extras = []
    for b in c["extra"]:
        if b["size"] < 2:
            continue
        f = (np.mean(pos[b["nodes"], UP]) - lo) / c["height"]
        side = "L" if b["lat_mean"] >= 0 else "R"
        if f > max(x["at_frac"] for x in arms):
            kind, anchor = f"horn_{side}", "mixamorig:Head"
        elif f < min(x["at_frac"] for x in legs):
            kind, anchor = "tail", "mixamorig:Hips"
        else:
            kind, anchor = f"wing_{side}", "mixamorig:Spine2"
        pts = resample(pos, longest_line(c, b), list(np.linspace(0, 1, links + 1))[1:])
        parent = anchor
        base = sum(1 for e in extras if e[0].startswith(kind))
        for k, q in enumerate(pts):
            nm = f"{kind}_{base + k + 1:02d}"
            add(nm, parent, q)
            parent = nm
            extras.append((nm, kind))

    names = [x[0] for x in spec]
    par = np.array([x[1] for x in spec], dtype=np.int32)
    joints = np.stack([x[2] for x in spec]).astype(np.float32)
    report = {"source_rig": rigged_glb, "generated_joints": int(len(parents)),
              "spine_len": len(spine), "extras": [e[0] for e in extras]}
    return names, par, joints, report


