def placeholder_skin(vertices, joints, parents):
    """Nearest bone-SEGMENT weights, so the GLB carries a valid skin.

    TokenRig discards these and predicts real weights; they only have to survive
    the round trip. Segment distance rather than joint distance, so limbs bind
    along their length instead of clustering at joints.
    """
    v = np.asarray(vertices, dtype=np.float64)
    best = np.full(len(v), np.inf)
    who = np.zeros(len(v), dtype=np.int64)
    for j, p in enumerate(parents):
        a, b = joints[j] if p < 0 else joints[p], joints[j]
        ab = b - a
        len2 = float(ab @ ab)
        t = np.zeros(len(v)) if len2 < 1e-12 else np.clip((v - a) @ ab / len2, 0, 1)
        d = np.linalg.norm(v - (a + t[:, None] * ab), axis=1)
        m = d < best
        best[m], who[m] = d[m], j
    skin = np.zeros((len(v), len(joints)), dtype=np.float32)
    skin[np.arange(len(v)), who] = 1.0
    return skin


def gltf_to_blender(v):
    """glTF Y-up -> Blender Z-up: (x, y, z) -> (x, -z, y).

    trimesh hands us glTF coordinates, but a bpy scene treats whatever it is given
    as Z-up and the glTF exporter then applies its OWN Y-up conversion on write.
    Without pre-converting, the two rotations compound and the character ships
    lying on its side - measured as extents [0.694, 0.365, 1.0] where the source
    asset is [0.694, 1.0, 0.365].
    """
    v = np.asarray(v, dtype=np.float64)
    out = np.empty_like(v)
    out[..., 0], out[..., 1], out[..., 2] = v[..., 0], -v[..., 2], v[..., 1]
    return out


def cmd_fit(args):
    import trimesh
    from src.rig_package.info.asset import Asset
    from src.rig_package.parser.bpy import BpyParser

    mesh = trimesh.load(args.mesh, force="mesh", process=False)
    if args.from_rig:
        names, parents, joints, gen_report = mixamo_from_generated(args.from_rig)
        extra_report = [{"from_generated": gen_report}]
        lm = {"mode": "from-rig", **gen_report}
    else:
        gen_report = None
        lm = landmarks(mesh)
        names, parents, joints = core_skeleton(lm)
        extra_report = []
    if not args.from_rig and not args.no_appendages:
        chains, extra_report = appendage_chains(lm, names, parents, joints)
        for nm, par, pos in chains:
            names.append(nm)
            parents = np.append(parents, par)
            joints = np.vstack([joints, pos[None, :]])
        joints = joints.astype(np.float32)

    skin = placeholder_skin(mesh.vertices, joints, parents)
    # Convert to Blender's axis convention before handing the data to bpy; the
    # exporter converts back on write. See gltf_to_blender.
    asset = Asset.from_data(
        vertices=gltf_to_blender(mesh.vertices).astype(np.float32),
        faces=np.asarray(mesh.faces, dtype=np.int64),
        joints=gltf_to_blender(joints).astype(np.float32),
        parents=parents, joint_names=names, skin=skin,
        armature_name="Armature",
    )
    BpyParser.export_asset(asset, args.out, do_not_normalize=True)

    report_path = args.out.rsplit(".", 1)[0] + "_skeleton.json"
    report = {
        "source": args.mesh, "out": args.out,
        "bones": len(names), "core_bones": len(names) - len(extra_report) * 3,
        "appendages": extra_report,
        "landmarks": {k: (round(v, 4) if isinstance(v, float) else v)
                      for k, v in lm.items() if k not in ("points",)},
        "names": names,
    }
    open(report_path, "w").write(json.dumps(report, indent=2))
    print(json.dumps(report, indent=2))
    print(f"CANONICAL_FIT_OK {args.out}")


