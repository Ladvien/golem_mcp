def _glb_chunks(path):
    data = open(path, "rb").read()
    magic, _ver, total = struct.unpack("<III", data[:12])
    if magic != 0x46546C67:
        raise SystemExit(f"{path} is not a GLB")
    chunks, off = [], 12
    while off < total:
        clen, ctype = struct.unpack("<II", data[off:off + 8])
        chunks.append([ctype, data[off + 8:off + 8 + clen]])
        off += 8 + clen
    return chunks


def cmd_restore(args):
    """Rename bone_i back to the supplied names, by index.

    Patches the GLB's JSON chunk in place. Re-exporting through bpy is what
    produced a skinless file in the first place; node names are plain strings, so
    rewriting them cannot disturb the skin, inverse-bind matrices or buffers.
    """
    ref = _glb_chunks(args.reference)
    ref_doc = json.loads(next(p for t, p in ref if t == GLTF_JSON_CHUNK).decode("utf-8"))
    wanted = [ref_doc["nodes"][i].get("name", "") for i in ref_doc["skins"][0]["joints"]]

    chunks = _glb_chunks(args.rigged)
    ji = next(i for i, c in enumerate(chunks) if c[0] == GLTF_JSON_CHUNK)
    doc = json.loads(chunks[ji][1].decode("utf-8"))
    joints = doc["skins"][0]["joints"]

    if len(joints) != len(wanted):
        raise SystemExit(
            f"joint count differs: rigged {len(joints)} vs reference {len(wanted)}. "
            "Rename-by-index is only valid when the skeleton was supplied and honoured - "
            "check that --use_skeleton was actually passed."
        )

    for slot, node in enumerate(joints):
        doc["nodes"][node]["name"] = wanted[slot]
    chunks[ji][1] = json.dumps(doc, separators=(",", ":")).encode("utf-8")

    out = b""
    for ctype, payload in chunks:
        pad = (4 - len(payload) % 4) % 4
        payload += (b" " if ctype == GLTF_JSON_CHUNK else b"\x00") * pad
        out += struct.pack("<II", len(payload), ctype) + payload
    open(args.out, "wb").write(struct.pack("<III", 0x46546C67, 2, 12 + len(out)) + out)

    print(json.dumps({"rigged": args.rigged, "out": args.out,
                      "renamed": len(wanted), "sample": wanted[:6]}, indent=2))
    print(f"CANONICAL_RESTORE_OK {args.out}")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    f = sub.add_parser("fit", help="write a mesh GLB carrying a Mixamo armature")
    f.add_argument("--mesh", required=True)
    f.add_argument("--out", required=True)
    f.add_argument("--no-appendages", action="store_true",
                   help="core skeleton only; skip wing/tail/horn chains")
    f.set_defaults(func=cmd_fit)

    r = sub.add_parser("restore-names", help="rename bone_N back to the supplied names")
    r.add_argument("--rigged", required=True)
    r.add_argument("--reference", required=True, help="the GLB produced by `fit`")
    r.add_argument("--out", required=True)
    r.set_defaults(func=cmd_restore)

    args = ap.parse_args()
    args.func(args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
